    @Test
    fun testProactiveCollaborationScope_FinancialIsolation() = runBlocking {
        val scopeRepo = ProactiveCollaborationScopeRepository.defaultInstance

        // Staff Sales Role -> Must be DEPARTMENT SCOPED and RESTRICTED from financial data
        val salesScope = scopeRepo.determineProactiveScope(
            staffId = "staff-sales-01",
            explicitJobLevel = "Sales Representative",
            explicitDepartment = "sales"
        )
        assertEquals("department_scoped", salesScope.scopeType)
        assertFalse(salesScope.hasFinancialAccess, "Sales staff must NOT have financial access")
        assertTrue(salesScope.financialDataRestricted, "Sales staff financial data must be restricted")
        assertNotNull(salesScope.collaboratingAiJobTitleIds)
        assertFalse(salesScope.collaboratingAiJobTitleIds!!.contains("finance"), "Sales AI collaboration scope must not include finance")

        // Executive / Owner Role -> EXECUTIVE FULL SUMMARY and FULL access
        val execScope = scopeRepo.determineProactiveScope(
            staffId = "staff-ceo-01",
            explicitJobLevel = "Chief Executive Officer / Direksi",
            explicitDepartment = "executive"
        )
        assertEquals("executive_full_summary", execScope.scopeType)
        assertTrue(execScope.hasFinancialAccess, "Executive must have financial access")
        assertFalse(execScope.financialDataRestricted, "Executive must not have financial restrictions")

        // ContextResolver test for Staff Daily Brief
        val salesBrief = ContextResolver.forStaffDailyBrief(
            staffId = "staff-sales-01",
            types = listOf("DAILY_BRIEF"),
            restrictToAiJobTitleIds = salesScope.collaboratingAiJobTitleIds
        )
        val hasCashFlow = salesBrief.any { str: String -> str.contains("Cash flow", ignoreCase = true) || str.contains("Finance", ignoreCase = true) }
        assertFalse(hasCashFlow, "Sales daily brief must NEVER leak cash flow or finance numbers")

        // Management Query Engine scope isolation
        val queryEngine = ManagementQueryEngine(ModelRouter())
        val financeQueryBySales = queryEngine.handleQuery(
            tenantId = "tenant-default",
            staffId = "staff-sales-01",
            staffProfile = null,
            queryText = "Berapa sisa kas dan saldo rekening bank kita?"
        )
        assertFalse(financeQueryBySales.allowed, "Query for cash/bank by sales staff must be disallowed")
        assertTrue(financeQueryBySales.responseText.contains("di luar cakupan", ignoreCase = true) || financeQueryBySales.responseText.contains("Direksi", ignoreCase = true))
    }

