            tenantId = "tenant-default",
            workflowDefId = "wf-chief-of-staff-briefing",
            prompt = "Sintesis briefing eksekutif pagi ini"
        )

        assertEquals("COMPLETED", execResult.status, "Workflow run must complete")
        assertEquals(5, execResult.nodeRuns.size, "All 5 nodes must be executed")
    }

