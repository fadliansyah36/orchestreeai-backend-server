    private fun generateHmacSha256(data: String, key: String): String {
        val sha256Hmac = Mac.getInstance("HmacSHA256")
        val secretKey = SecretKeySpec(key.toByteArray(Charsets.UTF_8), "HmacSHA256")
        sha256Hmac.init(secretKey)
        val signedBytes = sha256Hmac.doFinal(data.toByteArray(Charsets.UTF_8))
        return "sha256=" + signedBytes.joinToString("") { "%02x".format(it) }
    }

    @Test
    fun testWhatsAppWebhook_SignatureAndChannelPipeline() = runBlocking {
        val appSecret = "secret_meta_app_key_123"
        val payload = """{"senderId":"628123456789","senderName":"Pak Hendra","messageText":"Halo apa produk terlaris minggu ini?","tenantId":"tenant-default"}"""
        val validSig = generateHmacSha256(payload, appSecret)

        val handler = WhatsAppWebhookHandler()
        val result = handler.processInboundWebhook(
            payload = payload,
            signatureHeader = validSig,
            appSecret = appSecret,
            defaultTenantId = "tenant-default"
        )

        assertTrue(result.verified, "WhatsApp webhook signature must be verified")
        assertNotNull(result.conversationId, "Conversation ID must be generated")
        assertNotNull(result.replyText, "Outbound reply must be generated by ChannelGateway")
        assertEquals("628123456789", result.senderId)

        // Invalid signature test
        val invalidResult = handler.processInboundWebhook(
            payload = payload,
            signatureHeader = "sha256=invalid_signature_hash_value",
            appSecret = appSecret
        )
        assertFalse(invalidResult.verified, "Invalid signature must be rejected")
    }

