    @Test
    fun testProviderRegistryRepositoryOrdersProvidersByFallbackPriority() {
        val providers = providerRepo.getLlmProvidersOrderedByFallbackPriority()
        assertTrue(providers.isNotEmpty(), "Active providers must not be empty")

        // First provider must be OPENROUTER (fallback_priority 1)
        val first = providers.first()
        assertEquals("OPENROUTER", first.providerCode.uppercase())
        assertEquals(1, first.fallbackPriority)

        // Providers must be strictly ascending by fallbackPriority
        val priorities = providers.map { it.fallbackPriority }
        assertEquals(priorities.sorted(), priorities, "Providers must be strictly sorted by fallback_priority ascending")

        // Verify Gemini is NEVER the top provider
        assertFalse(providers.first().providerCode.equals("gemini", ignoreCase = true), "Gemini must never be top provider")

        // Verify Image provider default is GPT_IMAGE_2
        val imgProvider = providerRepo.getActiveImageProvider()
        assertEquals("GPT_IMAGE_2", imgProvider.providerCode.uppercase())
        assertEquals("gpt-image-2", imgProvider.defaultModel)
    }

    @Test
    fun testStartupValidationFailsClosedWhenGeminiInDatabaseWithoutApiKey() = runBlocking {
        val validator = StartupValidator(shouldExitProcessOnFailure = false)
        val stubRepo = object : ProviderRegistryRepository() {
            override fun getAllActive(): List<LlmProviderEntity> = listOf(
                LlmProviderEntity(
                    id = "llm-unauth-gemini",
                    name = "Google Gemini Unofficial",
                    providerCode = "GEMINI",
                    apiBaseUrl = "https://generativelanguage.googleapis.com",
                    apiKeyEnv = "PATH",
                    priority = 1,
                    fallbackPriority = 1,
                    taskSpecialization = "general"
                ),
                LlmProviderEntity(
                    id = "llm-groq",
                    name = "Groq",
                    providerCode = "GROQ",
                    apiBaseUrl = "https://api.groq.com/openai/v1",
                    apiKeyEnv = "PATH",
                    priority = 2,
                    fallbackPriority = 2,
                    taskSpecialization = "fast"
                )
            )
            override fun getLlmProvidersOrderedByFallbackPriority(): List<LlmProviderEntity> = getAllActive()
        }

        val ex = assertThrows<FatalConfigurationException> {
            validator.verifyNoHardcodedProviderFallback(stubRepo)
        }
        assertTrue(ex.message!!.contains("Google Gemini terkonfigurasi sebagai prioritas 1"), "Must reject Gemini entry as priority 1")
    }

    @Test
    fun testUniversalPromptComposerRoutesToConfiguredFallbackPriorityProvider() = runBlocking {
        val router = ModelRouter(
            config = AppConfig(environment = "production"),
            providerRepo = providerRepo,
            customProviders = mapOf(
                "openrouter" to mockOpenRouterClient,
                "groq" to mockGroqClient,
                "deepseek" to mockDeepSeekClient,
                "anthropic" to mockAnthropicClient,
                "gemini" to mockGeminiClient
            )
        )

        // Critical Point 1: Universal Prompt Composer (Fase 82)
        val req = ModelRouteRequest(
            taskCategory = "UNIVERSAL_PROMPT_COMPOSER",
            prompt = "Tuliskan strategi peluncuran produk enterprise B2B",
            tenantId = "tenant-test-1"
        )
        val res = router.route(req)
        assertTrue(res.isSuccess)
        val response = res.getOrThrow()

        // Must NOT call Gemini
        assertFalse(executionLog.contains("GEMINI"), "Universal Prompt Composer must NEVER call Gemini")
        // Must call OpenRouter or Groq based on fallback_priority
        assertTrue(executionLog.contains("OPENROUTER") || executionLog.contains("GROQ"))
        assertTrue(response.providerUsed.lowercase() in listOf("openrouter", "groq"))
    }

