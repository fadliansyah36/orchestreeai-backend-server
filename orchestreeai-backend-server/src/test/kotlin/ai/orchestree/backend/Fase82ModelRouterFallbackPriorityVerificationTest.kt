    @Test
    fun testFallbackChainExecutesInOrderWhenPrimaryFails() = runBlocking {
        val failingOpenRouter = object : LlmClient {
            override val providerId = "openrouter"
            override val providerName = "OpenRouter"
            override suspend fun complete(request: LlmRequest): Result<LlmResponse> {
                executionLog.add("OPENROUTER_FAILED")
                return Result.failure(RuntimeException("OpenRouter 503 Service Unavailable"))
            }
        }

        val router = ModelRouter(
            config = AppConfig(environment = "production"),
            providerRepo = providerRepo,
            customProviders = mapOf(
                "openrouter" to failingOpenRouter,
                "groq" to mockGroqClient,
                "deepseek" to mockDeepSeekClient,
                "anthropic" to mockAnthropicClient,
                "gemini" to mockGeminiClient
            )
        )

        val res = router.route(
            ModelRouteRequest(
                taskCategory = "GENERAL_CHAT",
                prompt = "Analisis kinerja keuangan kuartal 3 untuk seluruh divisi korporat secara komprehensif mencakup pendapatan operasional, laba bersih sebelum pajak, arus kas bebas, dan rasio solvabilitas jangka panjang secara mendalam dan terstruktur.",
                tenantId = "tenant-fallback-test"
            )
        )

        assertTrue(res.isSuccess)
        val resp = res.getOrThrow()

        // Must have failed on OpenRouter and fallen back to GROQ (fallback_priority 2)
        assertEquals(listOf("OPENROUTER_FAILED", "OPENROUTER_FAILED", "GROQ"), executionLog)
        assertEquals("groq", resp.providerUsed.lowercase())
        assertFalse(executionLog.contains("GEMINI"), "Fallback chain must not skip to Gemini when Groq is available")

        // Verify usage log in AnalyticsRepository
        val usageLogs = AnalyticsRepository.defaultInstance.getRecentLlmUsageLogs()
        val latestLog = usageLogs.lastOrNull { it.tenantId == "tenant-fallback-test" }
        assertNotNull(latestLog, "Usage log must be recorded in AnalyticsRepository")
        assertEquals("GROQ", latestLog!!.provider)
    }
